// Generates the dotted-continent data used by the globe and the flat map.
// Source: Natural Earth land polygons (world-atlas, public domain). Run: node scripts/build-globe-data.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';
import { geoContains } from 'd3-geo';

const topo = JSON.parse(readFileSync('node_modules/world-atlas/land-110m.json', 'utf8'));
const land = feature(topo, topo.objects.land);

function sample(step, equalArea) {
  const out = [];
  for (let lat = -58; lat <= 82; lat += step) {
    const lonStep = equalArea ? step / Math.max(0.2, Math.cos((lat * Math.PI) / 180)) : step;
    const offset = equalArea ? (Math.round(lat / step) % 2) * (lonStep / 2) : 0;
    for (let lon = -180 + offset; lon < 180; lon += lonStep) {
      if (geoContains(land, [lon, lat])) out.push(Math.round(lat * 100), Math.round(lon * 100));
    }
  }
  return out;
}
const encode = (values) => Buffer.from(new Int16Array(values).buffer).toString('base64');

const globe = sample(1.05, true);
const flat = sample(2.2, false);
writeFileSync(
  'src/components/globe/land-data.ts',
  `// Generated by scripts/build-globe-data.mjs — do not edit. Int16 pairs (lat × 100, lon × 100), base64.
export const GLOBE_LAND = '${encode(globe)}';
export const FLAT_LAND = '${encode(flat)}';

export function decodeLand(data: string): Int16Array {
  const binary = atob(data);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i);
  return new Int16Array(bytes.buffer);
}
`,
);
console.log('globe points', globe.length / 2, 'flat points', flat.length / 2);
